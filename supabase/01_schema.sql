-- Mshibe Group: Supabase / Postgres schema
-- Run in Supabase: SQL Editor > New query > paste > Run.
--
-- Matches models.py exactly: same table names, columns, lengths and nullability.
-- Money columns are double precision (= SQLAlchemy Float), and appointment date/time
-- stay text ("YYYY-MM-DD" / "HH:MM") because the app compares and parses them as strings.
-- Safe to run more than once.

-- ---------------------------------------------------------------- site settings
create table if not exists public.site_settings (
  id                   integer generated by default as identity primary key,
  company_name         varchar(120) default 'Mshibe Group',
  tagline              varchar(200) default 'Food. Appointments. Delivered.',
  about_text           text         default '',
  email                varchar(120) default 'MshibeGroup@gmail.com',
  phone                varchar(40)  default '',
  address              varchar(200) default 'Johannesburg, South Africa',
  delivery_fee         double precision default 25,
  currency_symbol      varchar(5)   default 'R',
  slot_duration        integer      default 30,
  open_time            varchar(5)   default '09:00',
  close_time           varchar(5)   default '17:00',
  working_days         varchar(20)  default '0,1,2,3,4',   -- 0 = Monday
  admin_username       varchar(60)  default 'admin',
  admin_password_hash  varchar(255)                        -- never expose (see 02_security.sql)
);

-- ---------------------------------------------------------------- food ordering
create table if not exists public.menu_categories (
  id             integer generated by default as identity primary key,
  name           varchar(80) not null,
  display_order  integer     default 0
);

create table if not exists public.menu_items (
  id           integer generated by default as identity primary key,
  category_id  integer      not null references public.menu_categories(id),
  name         varchar(120) not null,
  description  text         default '',
  price        double precision default 0,
  image_url    varchar(300) default '',
  available    boolean      not null default true,
  featured     boolean      default false
);
create index if not exists menu_items_category_idx on public.menu_items(category_id);

create table if not exists public.orders (
  id                integer generated by default as identity primary key,
  reference         varchar(12)  not null,
  customer_name     varchar(120) not null,
  customer_email    varchar(120) not null,
  customer_phone    varchar(40)  default '',
  delivery_address  varchar(300) default '',
  notes             text         default '',
  order_type        varchar(20)  default 'delivery',      -- delivery | pickup
  subtotal          double precision default 0,
  delivery_fee      double precision default 0,
  total             double precision default 0,
  status            varchar(20)  not null default 'pending',
  -- pending | preparing | ready | out_for_delivery | completed | cancelled
  created_at        timestamp    default now()            -- UTC
);
create unique index if not exists ix_orders_reference on public.orders(reference);
create index if not exists orders_status_idx  on public.orders(status);
create index if not exists orders_created_idx on public.orders(created_at desc);

create table if not exists public.order_items (
  id            integer generated by default as identity primary key,
  order_id      integer      not null references public.orders(id) on delete cascade,
  -- If a menu item is deleted later, past orders keep their snapshot name/price.
  menu_item_id  integer      references public.menu_items(id) on delete set null,
  name          varchar(120) not null,
  price         double precision not null,
  quantity      integer      default 1
);
create index if not exists order_items_order_idx on public.order_items(order_id);

-- ---------------------------------------------------------------- appointments
create table if not exists public.services (
  id           integer generated by default as identity primary key,
  name         varchar(120) not null,
  description  text         default '',
  duration     integer      default 30,                   -- minutes
  price        double precision default 0,
  icon         varchar(20)  default 'calendar',
  active       boolean      not null default true
);

create table if not exists public.appointments (
  id            integer generated by default as identity primary key,
  reference     varchar(12)  not null,
  service_id    integer      not null references public.services(id),
  client_name   varchar(120) not null,
  client_email  varchar(120) not null,
  client_phone  varchar(40)  default '',
  notes         text         default '',
  date          varchar(10)  not null,                   -- YYYY-MM-DD
  time          varchar(5)   not null,                   -- HH:MM
  status        varchar(20)  not null default 'pending',
  created_at    timestamp    default now()
);
create unique index if not exists ix_appointments_reference on public.appointments(reference);
create index if not exists ix_appointments_date on public.appointments(date);
create index if not exists appointments_service_idx on public.appointments(service_id);

-- Stops two people booking the same start time even if they click at the same moment.
-- Your app already treats any overlap as busy, so this only enforces what it intends.
create unique index if not exists appointment_no_double_booking
  on public.appointments(date, time) where status <> 'cancelled';

-- ---------------------------------------------------------------- contact form
create table if not exists public.contact_messages (
  id              integer generated by default as identity primary key,
  name            varchar(120) not null,
  email           varchar(120) not null,
  category        varchar(80)  not null,
  other_category  varchar(160) default '',
  subject         varchar(200) not null,
  message         text         not null,
  status          varchar(20)  not null default 'new',    -- new | read
  created_at      timestamp    default now()
);
create index if not exists contact_messages_status_idx on public.contact_messages(status, created_at desc);
